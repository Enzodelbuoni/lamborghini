/**
 * Measures where the two headlights are in every frame of clip 1 and writes
 * src/content/headlights.js, which drives the light beams in the hero.
 *
 * Usage (needs an ffmpeg binary):
 *   FFMPEG=/path/to/ffmpeg node scripts/track-headlights.mjs
 *
 * Method: frames are decoded at 180×320 in grayscale; in each half of the car
 * (left / right) the brightest blob between 30 % and 72 % of the height is the
 * headlight. Its size (number of near-white pixels) is the ignition level.
 * Once the car passes over the camera (≈ frame 145) the headlights leave the
 * frame, so their path is extrapolated and the light fades out.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const VIDEO = path.join(ROOT, 'public/videos/svj-approach.mp4')
const OUT = path.join(ROOT, 'src/content/headlights.js')
const FFMPEG = process.env.FFMPEG || 'ffmpeg'

const W = 180
const H = 320
const LAST_FRAME = 165 // last frame of clip 1 that is shown (see config/experience.js)
const TRACKED_UNTIL = 144 // after this the blobs are hood reflections, not headlights

const raw = execFileSync(FFMPEG, ['-v', 'error', '-i', VIDEO, '-vf', `scale=${W}:${H},format=gray`, '-f', 'rawvideo', '-'], {
  maxBuffer: 64 * 1024 * 1024,
})

const clamp01 = (v) => Math.min(1, Math.max(0, v))
const smoothstep = (a, b, x) => {
  const t = clamp01((x - a) / (b - a))
  return t * t * (3 - 2 * t)
}

/* ---------- 1. raw detection ---------- */

const detect = (frame, x0, x1) => {
  const base = frame * W * H
  const yA = Math.floor(H * 0.3)
  const yB = Math.floor(H * 0.72)
  let max = 0
  for (let y = yA; y < yB; y++) for (let x = x0; x < x1; x++) max = Math.max(max, raw[base + y * W + x])
  let sx = 0
  let sy = 0
  let n = 0
  for (let y = yA; y < yB; y++)
    for (let x = x0; x < x1; x++)
      if (raw[base + y * W + x] >= max - 12) {
        sx += x
        sy += y
        n++
      }
  return { u: sx / n / W, v: sy / n / H, n }
}

const frames = []
for (let f = 0; f <= LAST_FRAME; f++) frames.push({ L: detect(f, 0, W / 2), R: detect(f, W / 2, W) })

/* ---------- 2. smooth the tracked part, extrapolate the pass ---------- */

const smooth = (get, f, radius = 2) => {
  let sum = 0
  let count = 0
  for (let k = f - radius; k <= f + radius; k++) {
    if (k < 0 || k > TRACKED_UNTIL) continue
    sum += get(frames[k])
    count++
  }
  return sum / count
}

const track = []
for (let f = 0; f <= TRACKED_UNTIL; f++) {
  track.push([
    smooth((d) => d.L.u, f),
    smooth((d) => d.L.v, f),
    smooth((d) => d.R.u, f),
    smooth((d) => d.R.v, f),
  ])
}
const span = 4
const velocity = track[TRACKED_UNTIL].map((value, i) => (value - track[TRACKED_UNTIL - span][i]) / span)
for (let f = TRACKED_UNTIL + 1; f <= LAST_FRAME; f++) {
  const prev = track[f - 1]
  // keep spreading outwards, height stays where it was
  track.push([prev[0] + velocity[0], prev[1], prev[2] + velocity[2], prev[3]])
}

/* ---------- 3. light level ---------- */

// ignition read from the blob size, never going back down once lit
let lit = 0
const level = []
for (let f = 0; f <= LAST_FRAME; f++) {
  const ignition = f <= 48 ? clamp01((smooth((d) => (d.L.n + d.R.n) / 2, f) - 11) / (68 - 11)) : 1
  lit = Math.max(lit, ignition)
  const approach = 1 + 0.25 * smoothstep(60, 140, f) // the closer the car, the stronger the spill
  const pass = 1 - smoothstep(144, 156, f) // the car runs over the camera, headlights leave the frame
  level.push(lit * approach * pass)
}

/* ---------- 4. write the module ---------- */

const rows = track.map((p, f) => `  [${p.map((v) => v.toFixed(4)).join(', ')}, ${level[f].toFixed(3)}],`).join('\n')
const source = `/**
 * Headlight positions in clip 1, one row per frame (0–${LAST_FRAME}):
 *   [leftU, leftV, rightU, rightV, light]
 * u / v are relative to the 720×1280 video frame (0–1); light is the beam
 * level (0 = off, 1 = fully lit, up to 1.25 as the car gets close).
 *
 * Generated by scripts/track-headlights.mjs — do not edit by hand.
 */
export const HEADLIGHTS = [
${rows}
]
`
fs.writeFileSync(OUT, source)
console.log(`wrote ${path.relative(ROOT, OUT)} (${track.length} frames)`)
